#!/usr/bin/env node
/**
 * Generate src/data/threatActors.generated.js — the actor→technique map RECON
 * uses to name adversaries known for an incident's techniques.
 *
 * Authoritative technique mapping comes from MITRE ATT&CK's STIX (intrusion-set
 * "uses" attack-pattern), on disk at attack-data/mitre-cti. Country + suspected
 * state sponsor come from the MISP Galaxy threat-actor cluster, bundled as
 * src/data/threatActorCountries.json (a compact name/alias → {c,s} index), joined
 * by case-folded group name or any ATT&CK alias.
 *
 * This is naming LEADS, not attribution — many actors share a technique. The
 * client only surfaces actors with a real overlap and always labels it a lead.
 *
 * Usage: node tools/gen-threat-actors.mjs [--data DIR]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const arg = (name, fb) => { const i = process.argv.indexOf(name); return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fb; };
const DATA = arg('--data', process.env.ATTACK_DATA || '/home/claude/attack-data');
const parent = (id) => String(id).split('.')[0].toUpperCase();
const fold = (s) => String(s || '').toLowerCase().trim();

const bundle = JSON.parse(readFileSync(join(DATA, 'mitre-cti', 'enterprise-attack', 'enterprise-attack.json'), 'utf8'));
const countries = JSON.parse(readFileSync(join(ROOT, 'src', 'data', 'threatActorCountries.json'), 'utf8')).idx;

const ext = (o) => (o.external_references || []).find((r) => r.source_name === 'mitre-attack')?.external_id || null;
const groups = new Map(); // stix id -> { id, name, aliases, techniques:Set }
const techId = new Map(); // attack-pattern stix id -> parent technique id
for (const o of bundle.objects) {
  if (o.type === 'intrusion-set' && !o.revoked && !o.x_mitre_deprecated) {
    groups.set(o.id, { id: ext(o), name: o.name, aliases: o.aliases || o.x_mitre_aliases || [o.name], techniques: new Set() });
  }
  if (o.type === 'attack-pattern' && !o.revoked && !o.x_mitre_deprecated) {
    const id = ext(o); if (id) techId.set(o.id, parent(id));
  }
}
for (const o of bundle.objects) {
  if (o.type !== 'relationship' || o.relationship_type !== 'uses') continue;
  const g = groups.get(o.source_ref); const t = techId.get(o.target_ref);
  if (g && t) g.techniques.add(t);
}

const lookupCountry = (g) => {
  for (const name of [g.name, ...g.aliases]) { const hit = countries[fold(name)]; if (hit) return hit; }
  return null;
};

const actors = [...groups.values()]
  .filter((g) => g.id && g.techniques.size)
  .map((g) => {
    const cc = lookupCountry(g);
    return {
      id: g.id,
      name: g.name,
      aliases: [...new Set(g.aliases.filter((a) => fold(a) !== fold(g.name)))].slice(0, 4),
      country: cc?.c || null,
      sponsor: cc?.s || null,
      techniques: [...g.techniques].sort(),
    };
  })
  .sort((a, b) => a.id.localeCompare(b.id));

const attackVersion = (() => {
  try { return (bundle.objects.find((o) => o.type === 'x-mitre-collection')?.x_mitre_version) || null; } catch { return null; }
})();

const module = [
  '// GENERATED by tools/gen-threat-actors.mjs. Do not edit by hand.',
  '// Actor→technique map: MITRE ATT&CK groups (STIX "uses"); country/sponsor from',
  '// the MISP Galaxy threat-actor cluster (src/data/threatActorCountries.json).',
  `export const THREAT_ACTORS = Object.freeze(${JSON.stringify(actors)});`,
  '',
].join('\n');
writeFileSync(join(ROOT, 'src', 'data', 'threatActors.generated.js'), module);

const withCountry = actors.filter((a) => a.country).length;
console.log(`wrote src/data/threatActors.generated.js — ${actors.length} actors (${withCountry} with country), ATT&CK ${attackVersion || '?'}`);
console.log('sample:', actors.filter((a) => ['G0016', 'G0032', 'G0007'].includes(a.id)).map((a) => `${a.id} ${a.name} [${a.country || '?'}] ${a.techniques.length} techs`).join(' · '));
